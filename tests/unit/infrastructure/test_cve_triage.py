"""Unit tests for scripts/dev/cve-triage.py.

Protects the #37 triage invariants:
- An advisory is marked production exactly when its package is pinned in
  the ``uv export --no-dev`` requirements, whatever the name's spelling.
- A duplicated advisory (pip-audit lists some twice) yields one row.
- Production findings sort before dev-only ones.
- The exit code says whether the immediate-patch playbook can apply:
  0 clean, 1 production, 3 dev-only.
- The link points at the GHSA advisory when one exists, else OSV.
"""

import importlib.util
import json
import sys
from pathlib import Path

from hypothesis import given
from hypothesis import strategies as st

from tests.support.paths import REPO_ROOT

_SCRIPT_PATH = REPO_ROOT / "scripts" / "dev" / "cve-triage.py"
_spec = importlib.util.spec_from_file_location("cve_triage", _SCRIPT_PATH)
assert _spec is not None and _spec.loader is not None
triage = importlib.util.module_from_spec(_spec)
sys.modules["cve_triage"] = triage
_spec.loader.exec_module(triage)

_PROD_REQUIREMENTS = """\
# This file was autogenerated by uv via the following command:
#    uv export --frozen --no-dev --no-emit-project --no-hashes
idna==3.6
    # via httpx
python-telegram-bot==22.8
colorama==0.4.6 ; sys_platform == 'win32'
"""

_IDNA_VULN = {
    "id": "PYSEC-2024-60",
    "fix_versions": ["3.7"],
    "aliases": ["CVE-2024-3651", "GHSA-jjg7-2v4v-x38h"],
    "description": "quadratic encode",
}
_REQUESTS_VULN = {
    "id": "PYSEC-2026-1873",
    "fix_versions": ["2.32.0"],
    "aliases": ["GHSA-9wx4-h78v-vm56", "CVE-2024-35195"],
    "description": "verify=False sticks",
}


def _audit(*deps: tuple[str, str, list[dict[str, object]]]) -> dict[str, object]:
    return {
        "dependencies": [{"name": n, "version": v, "vulns": vulns} for n, v, vulns in deps],
        "fixes": [],
    }


def test_production_names_reads_pins_and_markers() -> None:
    """Every ``==`` pin is a production name, environment markers included."""
    names = triage.production_names(_PROD_REQUIREMENTS)
    assert names == frozenset({"idna", "python-telegram-bot", "colorama"})


def test_package_in_export_is_production() -> None:
    """A package pinned in the no-dev export is classed production."""
    prod = triage.production_names(_PROD_REQUIREMENTS)
    rows = triage.findings(_audit(("idna", "3.6", [_IDNA_VULN])), prod)
    assert [r.production for r in rows] == [True]


def test_package_missing_from_export_is_dev_only() -> None:
    """A package absent from the no-dev export is classed dev-only."""
    prod = triage.production_names(_PROD_REQUIREMENTS)
    rows = triage.findings(_audit(("requests", "2.31.0", [_REQUESTS_VULN])), prod)
    assert [r.production for r in rows] == [False]


def test_name_spelling_does_not_change_scope() -> None:
    """``Python_Telegram.Bot`` in the audit matches ``python-telegram-bot`` in the export."""
    prod = triage.production_names(_PROD_REQUIREMENTS)
    rows = triage.findings(_audit(("Python_Telegram.Bot", "22.8", [_IDNA_VULN])), prod)
    assert rows[0].production is True


@given(st.from_regex(r"[A-Za-z][A-Za-z0-9]{0,8}([-_.]{1,2}[A-Za-z0-9]{1,8}){0,3}", fullmatch=True))
def test_normalize_is_idempotent_and_separator_blind(name: str) -> None:
    """Normalizing twice changes nothing, and any separator run equals one hyphen."""
    once = triage.normalize(name)
    assert triage.normalize(once) == once
    assert triage.normalize(name.replace("-", "_")) == once


def test_duplicate_advisory_yields_one_row() -> None:
    """pip-audit's repeated (package, advisory) pairs collapse to one finding."""
    rows = triage.findings(
        _audit(("requests", "2.31.0", [_REQUESTS_VULN, _REQUESTS_VULN])), frozenset()
    )
    assert len(rows) == 1


def test_production_rows_sort_first() -> None:
    """Production findings lead the table so the urgent rows are read first."""
    prod = triage.production_names(_PROD_REQUIREMENTS)
    audit = _audit(("requests", "2.31.0", [_REQUESTS_VULN]), ("idna", "3.6", [_IDNA_VULN]))
    rows = triage.findings(audit, prod)
    assert [r.package for r in rows] == ["idna", "requests"]


def test_exit_code_production() -> None:
    """Any production finding exits 1."""
    prod = triage.production_names(_PROD_REQUIREMENTS)
    audit = _audit(("requests", "2.31.0", [_REQUESTS_VULN]), ("idna", "3.6", [_IDNA_VULN]))
    assert triage.exit_code(triage.findings(audit, prod)) == triage.EXIT_PRODUCTION


def test_exit_code_dev_only() -> None:
    """Dev-only findings alone exit 3, never 1."""
    rows = triage.findings(_audit(("requests", "2.31.0", [_REQUESTS_VULN])), frozenset())
    assert triage.exit_code(rows) == triage.EXIT_DEV_ONLY


def test_exit_code_clean() -> None:
    """No advisories exits 0 and prints the all-clear line."""
    rows = triage.findings(_audit(("idna", "3.19", [])), frozenset())
    assert triage.exit_code(rows) == triage.EXIT_CLEAN
    assert triage.render(rows) == "No known vulnerabilities found.\n"


def test_link_prefers_ghsa() -> None:
    """The link is the GitHub advisory, which carries the severity."""
    rows = triage.findings(_audit(("idna", "3.6", [_IDNA_VULN])), frozenset())
    assert rows[0].link == "https://github.com/advisories/GHSA-jjg7-2v4v-x38h"


def test_link_falls_back_to_osv() -> None:
    """Without a GHSA alias the link is the OSV record."""
    vuln = {"id": "PYSEC-2099-1", "fix_versions": [], "aliases": ["CVE-2099-1"]}
    rows = triage.findings(_audit(("idna", "3.6", [vuln])), frozenset())
    assert rows[0].link == "https://osv.dev/vulnerability/PYSEC-2099-1"


def test_render_marks_scope_and_missing_fix() -> None:
    """A row names its scope and says when no fixed version exists."""
    vuln = {"id": "PYSEC-2099-1", "fix_versions": [], "aliases": []}
    rows = triage.findings(_audit(("idna", "3.6", [vuln])), frozenset({"idna"}))
    row = triage.render(rows).splitlines()[2]
    assert row.startswith("| production | idna | 3.6 | PYSEC-2099-1 | - | no fix yet |")


def test_main_reads_files_and_returns_exit_code(tmp_path: Path) -> None:
    """With both inputs as files, main runs no tools and returns the triage exit code."""
    audit_path = tmp_path / "audit.json"
    audit_path.write_text(json.dumps(_audit(("idna", "3.6", [_IDNA_VULN]))), encoding="utf-8")
    req_path = tmp_path / "requirements.txt"
    req_path.write_text(_PROD_REQUIREMENTS, encoding="utf-8")
    code = triage.main(["--audit-json", str(audit_path), "--prod-requirements", str(req_path)])
    assert code == triage.EXIT_PRODUCTION


def test_main_rejects_malformed_json(tmp_path: Path) -> None:
    """Unparseable audit output is a usage error (2), never a silent all-clear."""
    audit_path = tmp_path / "audit.json"
    audit_path.write_text("not json", encoding="utf-8")
    req_path = tmp_path / "requirements.txt"
    req_path.write_text("", encoding="utf-8")
    code = triage.main(["--audit-json", str(audit_path), "--prod-requirements", str(req_path)])
    assert code == triage.EXIT_USAGE
