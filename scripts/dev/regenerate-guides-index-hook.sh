#!/usr/bin/env bash
# Pre-commit wrapper around regenerate-guides-index.sh.
#
# Runs the regen script, git-adds the result, and (if README.md actually
# changed) FAILS the commit with a clear "re-commit or --amend" hint. That
# converts the previous drift class — sub-agent commits with a stale
# docs/guides/README.md, pushes, pr-preflight/CI fails on "guides index
# stale" — into a caught-at-commit-time failure with an unambiguous fix.
#
# Why fail instead of silently patching the commit:
#   pre-commit stashes unstaged changes before hooks run and restores them
#   after. A `git add` from inside a hook does NOT get carried into the
#   in-progress commit — the stash-restore step un-does it. So the honest
#   pattern is: regenerate + stage the file for the NEXT operation, then
#   fail with a hint. The user's `git commit --amend --no-edit` (or a
#   fresh `git commit`) picks up the staged README.md and lands both
#   changes atomically.
#
# Called by:
#   `.pre-commit-config.yaml` — `regenerate-guides-index` hook, triggered
#   when any docs/guides/*.md file is staged.
#
# Invocation (production):
#   bash scripts/dev/regenerate-guides-index-hook.sh
#
# Self-test invocation (deterministic, no filesystem writes):
#   HERMES_SELF_TEST=1 bash scripts/dev/regenerate-guides-index-hook.sh
#
# Exit codes:
#   0 — README.md was already up to date (regen was a no-op)
#   1 — README.md was regenerated and staged; user must re-commit or --amend

set -uo pipefail

# ────────────────────────────────────────────────────────────────
# Self-test — verifies the regen script exists and produces
# a deterministic docs/guides/README.md snapshot. No filesystem
# mutation persists beyond the hook run.
# ────────────────────────────────────────────────────────────────
if [[ "${HERMES_SELF_TEST:-0}" == "1" ]]; then
    fail=0
    REPO_ROOT="$(cd "$(dirname "$0")/../.." && pwd)"

    if [[ ! -x "$REPO_ROOT/scripts/dev/regenerate-guides-index.sh" ]]; then
        echo "SELF-TEST FAIL: regenerate-guides-index.sh not found or not executable"
        fail=1
    else
        echo "PASS: regenerate-guides-index.sh is executable"
    fi

    if [[ ! -f "$REPO_ROOT/docs/guides/README.md" ]]; then
        echo "SELF-TEST FAIL: docs/guides/README.md missing"
        fail=1
    else
        echo "PASS: docs/guides/README.md exists"
    fi

    # Idempotence check: run the regen script, snapshot the file, run it
    # again, diff. Two consecutive runs on unchanged inputs MUST produce
    # identical output — otherwise the hook would flap between "clean"
    # and "regenerated" states across commits.
    tmp_snapshot=$(mktemp)
    if bash "$REPO_ROOT/scripts/dev/regenerate-guides-index.sh" >/dev/null 2>&1 \
        && cp "$REPO_ROOT/docs/guides/README.md" "$tmp_snapshot" \
        && bash "$REPO_ROOT/scripts/dev/regenerate-guides-index.sh" >/dev/null 2>&1 \
        && diff -q "$tmp_snapshot" "$REPO_ROOT/docs/guides/README.md" >/dev/null 2>&1; then
        echo "PASS: regen is idempotent (two consecutive runs produce identical output)"
    else
        echo "SELF-TEST FAIL: regen is not idempotent"
        fail=1
    fi
    rm -f "$tmp_snapshot"

    if [[ "$fail" == 1 ]]; then
        echo ""
        echo "SELF-TEST FAILED"
        exit 1
    fi
    echo ""
    echo "SELF-TEST PASS: regenerate-guides-index-hook.sh handles 3 fixtures."
    exit 0
fi

# ────────────────────────────────────────────────────────────────
# Production path
# ────────────────────────────────────────────────────────────────
REPO_ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
README="$REPO_ROOT/docs/guides/README.md"

# Snapshot README.md BEFORE running regen. If regen produces different
# content, we know README.md needs to be committed.
before_sha=""
if [[ -f "$README" ]]; then
    before_sha=$(git hash-object "$README" 2>/dev/null || echo "")
fi

# Run the actual regen. Its own errors (missing header metadata, etc.)
# surface via its non-zero exit — propagate them.
if ! bash "$REPO_ROOT/scripts/dev/regenerate-guides-index.sh"; then
    echo "ERROR: regenerate-guides-index.sh failed — see output above." >&2
    exit 1
fi

after_sha=""
if [[ -f "$README" ]]; then
    after_sha=$(git hash-object "$README" 2>/dev/null || echo "")
fi

if [[ "$before_sha" == "$after_sha" ]]; then
    # No change — commit proceeds as normal.
    exit 0
fi

# Regen produced a real diff. Stage the file so a follow-up
# `git commit --amend --no-edit` (or a fresh `git commit`) picks it up
# without the user needing to remember to stage it manually.
if ! git -C "$REPO_ROOT" add docs/guides/README.md; then
    echo "ERROR: failed to stage regenerated docs/guides/README.md" >&2
    exit 1
fi

{
    echo "ERROR: docs/guides/README.md was regenerated by the pre-commit hook."
    echo "       The refreshed file is now STAGED — pre-commit's stash-restore"
    echo "       mechanism prevents mid-hook git-add from carrying into the"
    echo "       current commit, so this commit was blocked."
    echo ""
    echo "  Fix (pick one):"
    echo "    * If the current commit has not landed yet (first attempt):"
    echo "        git commit --amend --no-edit"
    echo "      This folds the fresh README.md into the same commit."
    echo ""
    echo "    * If you want the README.md as a separate commit:"
    echo "        git commit -m 'docs(guides): regenerate index'"
    echo ""
    echo "  Why this happens: the guides index in docs/guides/README.md is"
    echo "  auto-generated from the H1 + Description + git log date of each"
    echo "  guide file. A commit that touches a guide file needs the index"
    echo "  refreshed atomically, or CI (guides-index-current job) fails."
    echo "  See docs/guides/README.md § Living index for the design."
} >&2
exit 1
